namespace MidiMazeClone
{
    /// <summary>
    /// A 5x7 pixel font for HUD text, defined as readable rows of '#' and ' '.
    /// Lower case letters are drawn as upper case. Unknown characters draw as a blank.
    /// </summary>
    public static class TinyFont
    {
        public const int GlyphWidth = 5;
        public const int GlyphHeight = 7;
        public const int Advance = 6;    // glyph width plus one pixel spacing

        private static readonly Dictionary<char, string[]> Glyphs = BuildGlyphs();

        public static string[]? GetGlyph(char c)
        {
            char key = char.ToUpperInvariant(c);
            string[]? rows;
            if (Glyphs.TryGetValue(key, out rows))
            {
                return rows;
            }
            return null;
        }

        private static void Add(Dictionary<char, string[]> glyphs, char c,
            string r0, string r1, string r2, string r3, string r4, string r5, string r6)
        {
            glyphs[c] = new string[] { r0, r1, r2, r3, r4, r5, r6 };
        }

        private static Dictionary<char, string[]> BuildGlyphs()
        {
            Dictionary<char, string[]> g = new Dictionary<char, string[]>();

            Add(g, 'A', " ### ", "#   #", "#   #", "#####", "#   #", "#   #", "#   #");
            Add(g, 'B', "#### ", "#   #", "#   #", "#### ", "#   #", "#   #", "#### ");
            Add(g, 'C', " ####", "#    ", "#    ", "#    ", "#    ", "#    ", " ####");
            Add(g, 'D', "#### ", "#   #", "#   #", "#   #", "#   #", "#   #", "#### ");
            Add(g, 'E', "#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#####");
            Add(g, 'F', "#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#    ");
            Add(g, 'G', " ####", "#    ", "#    ", "# ###", "#   #", "#   #", " ####");
            Add(g, 'H', "#   #", "#   #", "#   #", "#####", "#   #", "#   #", "#   #");
            Add(g, 'I', "#####", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "#####");
            Add(g, 'J', "    #", "    #", "    #", "    #", "#   #", "#   #", " ### ");
            Add(g, 'K', "#   #", "#  # ", "# #  ", "##   ", "# #  ", "#  # ", "#   #");
            Add(g, 'L', "#    ", "#    ", "#    ", "#    ", "#    ", "#    ", "#####");
            Add(g, 'M', "#   #", "## ##", "# # #", "#   #", "#   #", "#   #", "#   #");
            Add(g, 'N', "#   #", "##  #", "# # #", "#  ##", "#   #", "#   #", "#   #");
            Add(g, 'O', " ### ", "#   #", "#   #", "#   #", "#   #", "#   #", " ### ");
            Add(g, 'P', "#### ", "#   #", "#   #", "#### ", "#    ", "#    ", "#    ");
            Add(g, 'Q', " ### ", "#   #", "#   #", "#   #", "# # #", "#  # ", " ## #");
            Add(g, 'R', "#### ", "#   #", "#   #", "#### ", "# #  ", "#  # ", "#   #");
            Add(g, 'S', " ####", "#    ", "#    ", " ### ", "    #", "    #", "#### ");
            Add(g, 'T', "#####", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ");
            Add(g, 'U', "#   #", "#   #", "#   #", "#   #", "#   #", "#   #", " ### ");
            Add(g, 'V', "#   #", "#   #", "#   #", "#   #", "#   #", " # # ", "  #  ");
            Add(g, 'W', "#   #", "#   #", "#   #", "# # #", "# # #", "## ##", "#   #");
            Add(g, 'X', "#   #", "#   #", " # # ", "  #  ", " # # ", "#   #", "#   #");
            Add(g, 'Y', "#   #", "#   #", " # # ", "  #  ", "  #  ", "  #  ", "  #  ");
            Add(g, 'Z', "#####", "    #", "   # ", "  #  ", " #   ", "#    ", "#####");

            Add(g, '0', " ### ", "#   #", "#  ##", "# # #", "##  #", "#   #", " ### ");
            Add(g, '1', "  #  ", " ##  ", "  #  ", "  #  ", "  #  ", "  #  ", " ### ");
            Add(g, '2', " ### ", "#   #", "    #", "   # ", "  #  ", " #   ", "#####");
            Add(g, '3', "#####", "   # ", "  #  ", "   # ", "    #", "#   #", " ### ");
            Add(g, '4', "   # ", "  ## ", " # # ", "#  # ", "#####", "   # ", "   # ");
            Add(g, '5', "#####", "#    ", "#### ", "    #", "    #", "#   #", " ### ");
            Add(g, '6', "  ## ", " #   ", "#    ", "#### ", "#   #", "#   #", " ### ");
            Add(g, '7', "#####", "    #", "   # ", "  #  ", " #   ", " #   ", " #   ");
            Add(g, '8', " ### ", "#   #", "#   #", " ### ", "#   #", "#   #", " ### ");
            Add(g, '9', " ### ", "#   #", "#   #", " ####", "    #", "   # ", " ##  ");

            Add(g, ' ', "     ", "     ", "     ", "     ", "     ", "     ", "     ");
            Add(g, ':', "     ", "  #  ", "  #  ", "     ", "  #  ", "  #  ", "     ");
            Add(g, '.', "     ", "     ", "     ", "     ", "     ", " ##  ", " ##  ");
            Add(g, ',', "     ", "     ", "     ", "     ", "  ## ", "  ## ", " #   ");
            Add(g, '-', "     ", "     ", "     ", "#####", "     ", "     ", "     ");
            Add(g, '+', "     ", "  #  ", "  #  ", "#####", "  #  ", "  #  ", "     ");
            Add(g, '/', "    #", "    #", "   # ", "  #  ", " #   ", "#    ", "#    ");
            Add(g, '!', "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "     ", "  #  ");
            Add(g, '?', " ### ", "#   #", "    #", "   # ", "  #  ", "     ", "  #  ");
            Add(g, '%', "##  #", "##  #", "   # ", "  #  ", " #   ", "#  ##", "#  ##");
            Add(g, '(', "   # ", "  #  ", " #   ", " #   ", " #   ", "  #  ", "   # ");
            Add(g, ')', " #   ", "  #  ", "   # ", "   # ", "   # ", "  #  ", " #   ");

            return g;
        }
    }
}
